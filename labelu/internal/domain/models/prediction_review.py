"""Immutable audit records for PredictionSet review and legacy projection."""

from datetime import datetime

from sqlalchemy import Column, DateTime, ForeignKey, Index, Integer, String, Text
from sqlalchemy.schema import UniqueConstraint
from sqlalchemy import event

from labelu.internal.common.db import Base


class PredictionSetReviewAudit(Base):
    """Append-only record for each PredictionSet review state transition."""

    __tablename__ = "prediction_set_review_audit"
    __table_args__ = (
        UniqueConstraint(
            "prediction_set_id", "idempotency_key",
            name="uq_prediction_set_review_audit_request",
        ),
        Index(
            "idx_prediction_set_review_audit_set_time",
            "prediction_set_id", "created_at",
        ),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    prediction_set_id = Column(
        Integer, ForeignKey("prediction_set.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    project_id = Column(
        Integer, ForeignKey("project.id", ondelete="CASCADE"),
        nullable=True, index=True,
    )
    from_status = Column(String(24), nullable=False)
    to_status = Column(String(24), nullable=False)
    reason = Column(Text, nullable=True)
    actor_id = Column(Integer, ForeignKey("user.id"), nullable=False)
    idempotency_key = Column(String(128), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)


class PredictionSetProjection(Base):
    """One-way projection of an accepted prediction into legacy pre-annotation.

    The row is intentionally separate from ``TaskPreAnnotation`` so retries
    can return the original result without mutating either formal annotation
    data or an existing pre-annotation generated by another provider.
    """

    __tablename__ = "prediction_set_projection"
    __table_args__ = (
        UniqueConstraint("prediction_set_id", name="uq_prediction_set_projection_set"),
        UniqueConstraint("idempotency_key", name="uq_prediction_set_projection_request"),
        Index(
            "idx_prediction_set_projection_sample_time",
            "sample_id", "created_at",
        ),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    prediction_set_id = Column(
        Integer, ForeignKey("prediction_set.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    project_id = Column(
        Integer, ForeignKey("project.id", ondelete="CASCADE"),
        nullable=True, index=True,
    )
    provider_job_id = Column(
        Integer, ForeignKey("provider_job.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    task_id = Column(Integer, ForeignKey("task.id"), nullable=False, index=True)
    sample_id = Column(Integer, ForeignKey("task_sample.id"), nullable=False, index=True)
    pre_annotation_id = Column(
        Integer, ForeignKey("task_pre_annotation.id"), nullable=False, index=True,
    )
    payload_sha256 = Column(String(64), nullable=True)
    status = Column(String(24), nullable=False, default="PROJECTED")
    idempotency_key = Column(String(128), nullable=False)
    created_by = Column(Integer, ForeignKey("user.id"), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)
    metadata_json = Column(Text, nullable=True)


def _immutable(_mapper, _connection, _target):
    raise ValueError("prediction review audit records are immutable")


for _model in (PredictionSetReviewAudit, PredictionSetProjection):
    event.listen(_model, "before_update", _immutable)
    event.listen(_model, "before_delete", _immutable)
