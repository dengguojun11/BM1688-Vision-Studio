"""Regression coverage for the unified training snapshot retry path.

The training wizard submits a task-dimension request without ``label_ids`` for
the normal full-scope case.  A retry must reuse the frozen snapshot generated by
the first request; otherwise the second request reaches the immutable-manifest
duplicate guard and is surfaced as a misleading 409 to the UI.
"""

from __future__ import annotations

from fastapi.testclient import TestClient
from sqlalchemy.orm import Session

from labelu.internal.adapter.routers import training as training_router
from labelu.internal.domain.models.dataset import DatasetVersion
from labelu.tests.internal.application.service.test_dataset_version_label_subset import (
    _seed_two_label_task,
)


def test_unified_training_retry_reuses_full_scope_snapshot(
    client: TestClient,
    testuser_token_headers: dict[str, str],
    db: Session,
    monkeypatch,
):
    """Two identical unified requests create jobs against one immutable version."""

    _user, task, dataset, _labels = _seed_two_label_task(db)
    db.commit()

    # The test exercises request/lineage persistence, not a real worker run.
    monkeypatch.setattr(
        training_router,
        "enqueue_training_worker_command",
        lambda *args, **kwargs: None,
    )
    payload = {
        "task_id": task.id,
        "algorithm_key": "classification",
        "weights_source": "preset",
        "epochs": 1,
        "imgsz": 320,
        "execution_mode": "container",
        "container_image": "registry.example/classifier:test",
    }

    first = client.post(
        "/api/v1/training/jobs",
        headers=testuser_token_headers,
        json=payload,
    )
    assert first.status_code == 201, first.text

    second = client.post(
        "/api/v1/training/jobs",
        headers=testuser_token_headers,
        json=payload,
    )
    assert second.status_code == 201, second.text

    first_data = first.json()["data"]
    second_data = second.json()["data"]
    assert first_data["id"] != second_data["id"]
    assert first_data["dataset_version_id"] == second_data["dataset_version_id"]

    versions = (
        db.query(DatasetVersion)
        .filter(DatasetVersion.dataset_id == dataset.id)
        .all()
    )
    assert len(versions) == 1
    assert versions[0].id == first_data["dataset_version_id"]
