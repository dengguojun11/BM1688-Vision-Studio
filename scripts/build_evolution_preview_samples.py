"""Build a deduplicated real-sample reel for the evolution-screen preview."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / ".tmp/local-runtime-data/media/yolo_train"
FRONTEND_ROOT = ROOT / "frontend/labelU-Kit/apps/frontend"
OUTPUT_ROOT = FRONTEND_ROOT / "public/preview/samples"
MANIFEST_PATH = (
    FRONTEND_ROOT
    / "src/pages/platform/evolution/previewSamples.generated.ts"
)
SPLIT_LABELS = {"train": "训练集", "val": "验证集", "test": "测试集"}
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}


def main() -> None:
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    for old_image in OUTPUT_ROOT.glob("*.jpg"):
        old_image.unlink()

    samples: list[dict[str, str]] = []
    seen_hashes: set[str] = set()
    candidates = sorted(
        (
            path
            for path in SOURCE_ROOT.glob("job-*/dataset/images/*/*")
            if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
        ),
        key=lambda path: (
            -int(path.parents[3].name.removeprefix("job-")),
            path.parent.name,
            path.name,
        ),
    )

    for source in candidates:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if digest in seen_hashes:
            continue
        seen_hashes.add(digest)

        job_id = source.parents[3].name.removeprefix("job-")
        split = source.parent.name
        output_name = f"{len(samples) + 1:03d}-{source.stem}.jpg"
        target = OUTPUT_ROOT / output_name
        with Image.open(source) as original:
            image = ImageOps.exif_transpose(original).convert("RGB")
            image.thumbnail((960, 540), Image.Resampling.LANCZOS)
            image.save(target, quality=84, optimize=True)

        samples.append(
            {
                "id": digest[:16],
                "url": f"/preview/samples/{output_name}",
                "fileName": source.name,
                "dataset": f"训练任务 {job_id}",
                "split": SPLIT_LABELS.get(split, split),
            }
        )

    if not samples:
        raise RuntimeError(f"No dataset images found under {SOURCE_ROOT}")

    manifest = (
        "/* Generated by scripts/build_evolution_preview_samples.py. */\n"
        "export interface EvolutionPreviewSample {\n"
        "  id: string;\n"
        "  url: string;\n"
        "  fileName: string;\n"
        "  dataset: string;\n"
        "  split: string;\n"
        "}\n\n"
        "export const evolutionPreviewSamples: EvolutionPreviewSample[] = "
        + json.dumps(samples, ensure_ascii=False, indent=2)
        + ";\n"
    )
    MANIFEST_PATH.write_text(manifest, encoding="utf-8")
    print(f"Generated {len(samples)} unique real samples from {len(list(SOURCE_ROOT.glob('job-*')))} training jobs")


if __name__ == "__main__":
    main()
